@st.cache_resource
def train_reinsurance_tree():
    """Trains the ML model to recommend Reinsurance treaties based on risk/capital ratios."""
    X = np.array([
        [0.05, 0.1], [0.08, 0.2],  # Low loss ratio, low severity -> Retain (0)
        [0.15, 0.8], [0.20, 0.9],  # Medium loss ratio, high frequency -> Quota Share (1)
        [0.40, 0.3], [0.60, 0.2],  # High loss ratio, massive single severity -> Excess of Loss (2)
        [0.85, 0.9], [0.95, 0.8]   # Company killer (High ratio, high severity) -> Facultative (3)
    ])
    y = np.array([0, 0, 1, 1, 2, 2, 3, 3])
    tree = DecisionTreeClassifier(max_depth=3, random_state=42)
    tree.fit(X, y)
    return tree

decision_tree = train_reinsurance_tree()

