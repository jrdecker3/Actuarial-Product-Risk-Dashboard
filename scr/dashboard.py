@st.cache_data
def load_master_data():
    import os
    
    # 1. Dynamically find where dashboard.py lives (the 'scr' folder)
    current_dir = os.path.dirname(os.path.abspath(__file__))
    
    # 2. Step UP one level to the main 'ACTUARIAL DASHBOARD' folder
