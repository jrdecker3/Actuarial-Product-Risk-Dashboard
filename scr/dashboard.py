    path_in_root = os.path.join(parent_dir, 'prodliab_pos_98-07.csv')
    path_in_data = os.path.join(parent_dir, 'data', 'prodliab_pos_98-07.csv')
    
    # 4. Have Python automatically select the right one
    if os.path.exists(path_in_data):
        file_path = path_in_data
    elif os.path.exists(path_in_root):
        file_path = path_in_root
    else:
        raise FileNotFoundError("Could not find the CSV in the main folder or the data folder.")

